const fs = require("fs"), assert = require("assert");
const root = require("path").join(__dirname, "../src/web");
const files = fs.readFileSync(root + "/js/files.js", "utf8");
const core = fs.readFileSync(root + "/js/core.js", "utf8");
assert(files.includes("pane.crumbs.hidden = false"), "path bars are always shown so both panels stay level");
assert(files.includes("Could not connect: ${files.lastError}"), "a failed connection is explained in the panel");
assert(/icon: iconName = "info"/.test(core) && core.includes("okButton.replaceChildren(icon("), "question windows carry an icon and keep the icon on the main button");
const html = fs.readFileSync(root + "/index.html", "utf8");
const defs = new Set([...html.matchAll(/<symbol id="i-([\w-]+)"/g)].map((m) => m[1]));
for (const m of files.matchAll(/ask\(\{[^}]*icon: "([\w-]+)"/g)) assert(defs.has(m[1]), "missing icon " + m[1]);
assert(files.includes('function clearFileDropState()'), "FTP drop indicators have a single cleanup path");
assert(files.includes('pane.root.classList.remove("drop", "drop-os")'), "both internal and OS drop indicators are cleared");
assert(files.includes('document.addEventListener("visibilitychange"'), "drop indicators are cleared when the app is hidden");
const devices = fs.readFileSync(root + "/js/devices.js", "utf8");
assert(devices.includes('typeof filesLeave === "function"'), "leaving the FTP page clears any active drop indicator");
const css = fs.readFileSync(root + "/app.css", "utf8");
assert(!/\.pane\.drop(?:-os)?\s*\{[^}]*outline\s*:/s.test(css), "FTP drop state does not draw a dashed outline");
assert(css.includes('border-color: color-mix(in srgb, var(--accent) 62%, var(--border))'), "FTP drop state uses a continuous subtle border");
console.log("files page: all checks passed");
